const COMMANDS = [
  "node --test tests/*.test.mjs",
  "npm test",
  "node --test tests/layout.test.mjs",
];

/**
 * Compute the replies still pending for a thread. Pure and reproducible:
 * the same thread.scriptStep, thread.id, thread.title and state.seed always give the same output.
 * Returns drafts: { authorId, kind, body, diff?, verification?, setStatus? }.
 */
export function nextReplies(thread, state) {
  const drafts = [];
  for (let step = thread.scriptStep; step < SCRIPT_LENGTH; step++) {
    const rng = mulberry32(hashString(`${state.seed}:${thread.id}:${step}`));
    drafts.push(buildStep(step, thread, rng));
  }
  return drafts;
}

function buildStep(step, thread, rng) {
  switch (step) {
    case 0:
      return {
        authorId: AGENT_IDS.planner,
        kind: "progress",
        body:
          `Plan for "${thread.title}":\n` +
          "1. Reproduce the problem.\n2. Draft a small change.\n3. Ask for review.\n4. Record a verification.\n" +
          "(SIMULATED fixed outline. No real analysis was performed.)",
        setStatus: "in_progress",
      };
    case 1: {
      const variant = pick(rng, DIFF_VARIANTS);
      return {
        authorId: AGENT_IDS.coder,
        kind: "diff",
        body: `Proposed change for ${variant.filename}. Illustrative only. (SIMULATED, not generated by a real model.)`,
        diff: { filename: variant.filename, unified: variant.unified },
      };
    }
    case 2:
      return {
        authorId: AGENT_IDS.reviewer,
        kind: "progress",
        body: pick(rng, REVIEW_NOTES),
      };
    default: {
      const command = pick(rng, COMMANDS);
      const result = rng() < 0.75 ? "pass" : "fail";
      return {
        authorId: AGENT_IDS.verifier,
        kind: "verification",
        body:
          result === "pass"
            ? "Verification record: checks reported as passing. (SIMULATED, no command was run.)"
            : "Verification record: checks reported as failing. (SIMULATED, no command was run.)",
        verification: { command, result, simulated: true },
        setStatus: result === "pass" ? "verified" : "blocked",
      };
    }
  }
}

export function isAgentId(id) {
  return ROSTER.some((a) => a.id === id);
}
